import type { Conversation, TranscriptMessage } from "./types.ts";

type Line = [string, string, string];

function chat(externalId: string, language: string, lines: Line[], channel = "agent chat", audioUrl: string | null = null): Conversation {
  const messages: TranscriptMessage[] = lines.map(([timestampRaw, speaker, text], messageIndex) => ({
    messageIndex,
    timestampRaw,
    speaker,
    text,
  }));
  return {
    id: `DEMO::${externalId}`,
    datasetGroupId: "DEMO",
    externalId,
    channel,
    language,
    audioUrl,
    origin: "demo",
    messages,
  };
}

